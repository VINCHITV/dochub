# ---------------------------------------------------------------------------
# Hallucination detection helper
# ---------------------------------------------------------------------------

_NUMBER_RE = re.compile(r"\b\d+(?:[.,]\d+)?%?\b")


def _detect_hallucinations(prd_text: str, transcript_text: str) -> int:
    """
    Regex-based hallucination counter.

    Finds all numeric claims (integers, decimals, percentages) in the generated
    PRD and checks how many of them appear anywhere in the original transcript.
    Returns the count of numbers/percentages present in the PRD but absent from
    the transcript — these are potential hallucinations.

    The check is deliberately loose (substring match) to minimise false positives.
    LLM-as-judge is deferred — this is a fast heuristic only.
    """
    prd_numbers = set(_NUMBER_RE.findall(prd_text))
    if not prd_numbers:
        return 0
    missing = 0
    for num in prd_numbers:
        if num not in transcript_text:
            missing += 1
    return missing


# ---------------------------------------------------------------------------
# SSE helper
# ---------------------------------------------------------------------------


def _sse(payload: dict) -> str:
    """Serialise a dict to a well-formed SSE data line."""
    return f"data: {json.dumps(payload)}\n\n"


_HEARTBEAT = 'data: {"heartbeat": true}\n\n'


