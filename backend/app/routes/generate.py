@router.post("/stories")
async def generate_stories(
    body: GenerateStoriesRequest,
    db: Annotated[Session, Depends(get_session)],
) -> StreamingResponse:
    """
    Stream user story generation as Server-Sent Events (3-step pipeline).

    Validates project status before opening the stream; returns 4xx on error
    (before StreamingResponse starts, normal JSON error responses are still possible).
    """
    statement = select(Project).where(Project.id == body.project_id)
    project: Optional[Project] = db.exec(statement).first()

    if project is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Project '{body.project_id}' not found.",
        )

    # Allow re-generation from STORIES_GENERATED (produces a diff against existing rows).
    _allowed_for_stories = {WorkflowStatus.PRD_APPROVED, WorkflowStatus.STORIES_GENERATED}
    if project.status not in _allowed_for_stories:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=(
                f"Story generation requires status PRD_APPROVED or STORIES_GENERATED; "
                f"current status is '{project.status.value}'."
            ),
        )

    if not project.prd_json:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Project has no PRD content. Generate and approve the PRD first.",
        )

    prd_data: dict
    try:
        prd_data = json.loads(project.prd_json)
    except json.JSONDecodeError as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Stored prd_json is corrupted: {exc}",
        ) from exc

    project_id = project.id

    # Load existing stories for diff comparison on re-generation.
    existing_stories: list[UserStory] = list(
        db.exec(select(UserStory).where(UserStory.project_id == project_id)).all()
    )

    return StreamingResponse(
        _stories_stream(project_id, prd_data, existing_stories),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
        },
    )


async def _stories_stream(
    project_id: str,
    prd_data: dict,
    existing_stories: "list[UserStory] | None" = None,
) -> AsyncGenerator[str, None]:
    """
    Async generator for the 3-step user story pipeline.

    Owns its own SQLModel Session (opened via `with Session(engine)`) so that
    FastAPI's dependency cleanup cannot close the session mid-stream.

    Step 1: Extract CapabilityList from PRD content (non-streamed, emits status event).
    Step 2: Generate SlicePlan (max 7 vertical slices).
    Step 3: Generate one UserStoryModel per slice, save each to DB immediately.

    All UserStory rows are saved inside the generator so partial results are
    durable if the connection drops after some stories are streamed.
    """
    # Build a compact PRD summary for the capability extraction prompt
    prd_summary = _flatten_prd_for_prompts(prd_data)

    # ------------------------------------------------------------------
    # Step 1 — Extract capabilities
    # ------------------------------------------------------------------
    yield _sse({"step": "extracting_capabilities"})
    yield _HEARTBEAT

    system_capabilities = (
        "You are a senior product manager. Extract a list of DISTINCT PRODUCT CAPABILITIES "
        "from the PRD provided. Each capability is a concrete function the product must perform "
        "(e.g. 'User can reset password via email link'). Be exhaustive but not redundant."
    )
    user_capabilities = f"PRD CONTENT:\n{prd_summary}\n\nExtract all product capabilities."

    try:
        capability_result, _, _ = await generate_section(
            section_name="capabilities",
            section_model=CapabilityList,
            system_prompt=system_capabilities,
            user_prompt=user_capabilities,
            project_id=project_id,
        )
    except Exception as exc:
        yield _sse({"error": f"Capability extraction failed: {exc}", "done": True})
        return

    capabilities_text = "\n".join(f"- {c}" for c in capability_result.capabilities)

    # ------------------------------------------------------------------
    # Step 2 — Generate vertical slices (max 7)
    # ------------------------------------------------------------------
    yield _HEARTBEAT

    system_slices = (
        "You are a senior product manager. Given a list of product capabilities, define "
        "VERTICAL SLICES for user story generation. Each slice is a thin, end-to-end user "
        "interaction that delivers independent value (no horizontal/technical-layer slices). "
        "Return AT MOST 7 slices. Prioritise by business value descending."
    )
    user_slices = (
        f"CAPABILITIES:\n{capabilities_text}\n\n"
        "Define vertical slices for user story generation. Maximum 7 slices."
    )

    try:
        slice_result, _, _ = await generate_section(
            section_name="slices",
            section_model=SlicePlan,
            system_prompt=system_slices,
            user_prompt=user_slices,
            project_id=project_id,
        )
    except Exception as exc:
        yield _sse({"error": f"Slice planning failed: {exc}", "done": True})
        return

    slices = slice_result.slices[:7]  # enforce max 7 at service boundary
    yield _sse({"step": "slices_planned", "count": len(slices)})

    # ------------------------------------------------------------------
    # Step 3 — Generate one UserStoryModel per slice
    # ------------------------------------------------------------------
    system_story = (
        "You are a senior product manager writing user stories. For the given slice:\n"
        "- title: short imperative title (e.g. 'Reset password via email')\n"
        "- description: must follow EXACTLY 'As a <persona>, I want <action>, so that <benefit>.'\n"
        "- acceptance_criteria: list covering happy path, at least one alternative path, "
        "and at least one error path. Each item is a complete sentence.\n"
        "- validations: list of field-level validation rules "
        "(field, rule, error_message). Include at least one row per form field implied by the slice.\n"
        "- priority: 'high' for must-have features (core user flow, blocking launch), "
        "'medium' for should-have (significant value, not launch-blocking), "
        "'low' for nice-to-have (enhancement, can defer). Base this on business impact from the PRD.\n"
        "- dependencies: list of OTHER story titles (from the same slice list) that must be "
        "completed before this story can begin. Use exact story titles. Empty list if none.\n"
        "- reference_links: list of documentation URLs or knowledge base references relevant "
        "to this story. Empty list if none."
    )

    # Collect all generated story models before diffing and persisting.
    # This allows classify_stories() to compare the full new set against existing rows.
    generated_story_models: list[UserStoryModel] = []

    for idx, slice_description in enumerate(slices):
        yield _HEARTBEAT

        user_story_prompt = (
            f"PRD CONTEXT:\n{prd_summary}\n\n"
            f"SLICE TO IMPLEMENT:\n{slice_description}\n\n"
            f"CAPABILITIES:\n{capabilities_text}\n\n"
            f"Write a complete user story for slice {idx + 1} of {len(slices)}."
        )

        try:
            story_model, _, _ = await generate_section(
                section_name=f"story_{idx + 1}",
                section_model=UserStoryModel,
                system_prompt=system_story,
                user_prompt=user_story_prompt,
                project_id=project_id,
            )
        except Exception as exc:
            yield _sse({"error": f"Story {idx + 1} generation failed: {exc}", "done": True})
            return

        generated_story_models.append(story_model)

    # ------------------------------------------------------------------
    # Diff new stories against existing rows (if any)
    # ------------------------------------------------------------------
    diff_result = classify_stories(
        existing=existing_stories or [],
        new_models=generated_story_models,
    )

    # ------------------------------------------------------------------
    # Persist diff results and stream story_done events
    # ------------------------------------------------------------------
    for entry in diff_result.entries:
        with Session(engine) as db:
            if entry.classification == "new":
                sm = entry.new_model
                story_row = UserStory(
                    project_id=project_id,
                    title=sm.title,
                    description=sm.description,
                    acceptance_criteria=json.dumps(sm.acceptance_criteria),
                    validations=json.dumps([v.model_dump() for v in sm.validations]),
                    priority=sm.priority,
                    dependencies=json.dumps(sm.dependencies),
                    reference_links=json.dumps(sm.reference_links),
                    story_status="open",
                )
                db.add(story_row)
                db.commit()
                db.refresh(story_row)
                story_id = story_row.id

            elif entry.classification == "modified":
                sm = entry.new_model
                existing_row = db.get(UserStory, entry.existing_id)
                if existing_row is not None:
                    existing_row.title = sm.title
                    existing_row.description = sm.description
                    existing_row.acceptance_criteria = json.dumps(sm.acceptance_criteria)
                    existing_row.validations = json.dumps([v.model_dump() for v in sm.validations])
                    existing_row.priority = sm.priority
                    existing_row.dependencies = json.dumps(sm.dependencies)
                    existing_row.reference_links = json.dumps(sm.reference_links)
                    db.add(existing_row)
                    db.commit()
                story_id = entry.existing_id

            elif entry.classification == "kept":
                story_id = entry.existing_id

            else:  # obsolete
                obsolete_row = db.get(UserStory, entry.existing_id)
                if obsolete_row is not None and obsolete_row.story_status != "done":
                    obsolete_row.story_status = "obsolete"
                    db.add(obsolete_row)
                    db.commit()
                # Emit a diff event (no story_done for obsolete)
                yield _sse({
                    "step": "story_diff",
                    "classification": "obsolete",
                    "story_id": entry.existing_id,
                    "title": entry.existing_title,
                })
                continue

        # Stream story_done event for new/modified/kept stories
        sm = entry.new_model
        yield _sse({
            "step": "story_done",
            "story": {
                "id": story_id,
                "title": sm.title,
                "description": sm.description,
                "acceptance_criteria": sm.acceptance_criteria,
                "validations": [v.model_dump() for v in sm.validations],
                "priority": sm.priority,
                "dependencies": sm.dependencies,
                "reference_links": sm.reference_links,
                "story_status": "open" if entry.classification in ("new", "modified") else "done",
            },
            "diff": entry.classification,
        })

    # ------------------------------------------------------------------
    # Advance workflow: PRD_APPROVED → STORIES_GENERATED
    # Re-generation from STORIES_GENERATED: already at the correct status.
    # advance_status is idempotent — calling it when already at STORIES_GENERATED
    # returns without error (it just detects it's already there).
    # ------------------------------------------------------------------
    advance_error: Optional[str] = None
    with Session(engine) as db:
        try:
            advance_status(project_id, WorkflowStatus.PRD_APPROVED, db)
        except HTTPException as exc:
            # 409 here means the status was not PRD_APPROVED — i.e. it was
            # STORIES_GENERATED (re-generation pass). That is expected and fine.
            if "STORIES_GENERATED" not in exc.detail:
                advance_error = exc.detail

    if advance_error is not None:
        yield _sse({"error": f"Workflow advance failed: {advance_error}", "done": True})
        return

    yield _sse({"done": True})


def _flatten_prd_for_prompts(prd_data: dict) -> str:
    """
    Convert the stored prd_data dict (with nested section dicts) into a
    compact plain text summary for use in story generation prompts.

    Each section dict is flattened to its key string fields, skipping
    internal metadata fields (source_doc_ids, type1_conflicts raw objects).
    """
    lines: list[str] = []

    section_order = ["title", "description", "problem", "why", "success", "audience", "open_questions"]
    for key in section_order:
        section = prd_data.get(key)
        if not section or not isinstance(section, dict):
            continue
        lines.append(f"\n## {key.upper()}")
        for field, value in section.items():
            if field == "source_doc_ids":
                continue
            if field == "type1_conflicts":
                # Flatten conflict entries to plain text
                if isinstance(value, list):
                    for conflict in value:
                        if isinstance(conflict, dict):
                            lines.append(
                                f"  [CONFLICT] {conflict.get('conflicting_statement', '')} → "
                                f"{conflict.get('proposed_change', '')} "
                                f"(severity: {conflict.get('severity', '')})"
                            )
                continue
            if isinstance(value, list):
                for item in value:
                    if isinstance(item, dict):
                        # GapEntry objects: show question text only
                        lines.append(f"  - {item.get('question', item)}")
                    else:
                        lines.append(f"  - {item}")
            elif value is not None:
                lines.append(f"  {field}: {value}")

    return "\n".join(lines)
