@router.post("/{project_id}/upload-refined-prd", status_code=status.HTTP_200_OK)
async def upload_refined_prd(
    project_id: str,
    file: UploadFile,
    db: Annotated[Session, Depends(get_session)],
) -> dict:
    """
    Replace a project's prd_json with content from a user-refined .docx file,
    then regenerate the open_questions section against the current KB.

    Accepted file types: .docx only (422 for anything else).

    Allowed project statuses: PRD_GENERATED or PRD_APPROVED.
      - If PRD_APPROVED, the project is reset to PRD_GENERATED so the user can
        re-approve the updated PRD before generating stories.
      - STORIES_GENERATED and later states are rejected with 409 — a regenerate
        would silently invalidate already-generated stories or Jira tickets.

    The open_questions section is always regenerated (not taken from the DOCX)
    because it depends on the current KB state, not just the uploaded text.

    Returns
    -------
    {
        "project_id": str,
        "status": str,                  # project.status after write
        "open_questions": dict,         # model_dump() of OpenQuestionsSection
    }
    """
    # --- File type guard ---
    filename: str = file.filename or ""
    if not filename.lower().endswith(".docx"):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Only .docx files are accepted for refined PRD upload.",
        )

    # --- Load project ---
    statement = select(Project).where(Project.id == project_id)
    project: Optional[Project] = db.exec(statement).first()

    if project is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Project '{project_id}' not found.",
        )

    if project.status not in _REFINED_PRD_ALLOWED_STATUSES:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=(
                f"Refined PRD upload requires project status PRD_GENERATED or PRD_APPROVED; "
                f"current status is '{project.status.value}'."
            ),
        )

    # --- Parse DOCX sections ---
    content: bytes = await file.read()
    try:
        prd_sections: dict[str, str] = parse_docx_by_headings(content)
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Failed to parse .docx file: {exc}",
        ) from exc

    if not prd_sections:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=(
                "The uploaded .docx contained no recognisable Heading 1 sections. "
                "Ensure the document uses Heading 1 style for all section titles."
            ),
        )

    # --- RAG retrieval for KB context (sync — offload to threadpool) ---
    start_ts = time.monotonic()
    chroma_client = get_chroma_client()
    collection = get_or_create_collection(chroma_client)
    retriever = HybridRetriever(collection, top_k=5)

    # Use the description section (truncated to 500 chars) as the retrieval query.
    # Fall back to title text, then to an empty string (returns [] from retriever).
    rag_query: str = (
        prd_sections.get("description", "")
        or prd_sections.get("title", "")
    )[:500]

    try:
        retrieved_nodes = await asyncio.to_thread(
            retriever.retrieve,
            rag_query,
            5,           # top_k positional arg
            project_id,  # project_id positional arg
        )
    except RuntimeError as exc:
        # KB unavailable — non-fatal; proceed without KB context.
        logger.warning(
            "projects.upload_refined_prd.rag_failed",
            project_id=project_id,
            error=str(exc),
        )
        retrieved_nodes = []

    # Build rag_context string for open_questions prompt injection
    rag_context_parts: list[str] = []
    for nws in retrieved_nodes:
        meta = nws.node.metadata
        doc_id = meta.get("doc_id", "unknown")
        section = meta.get("section", "")
        text = nws.node.get_content()
        rag_context_parts.append(f"[Source: {doc_id} / {section}]\n{text}")
    rag_context: str = (
        "\n\n---\n\n".join(rag_context_parts)
        if rag_context_parts
        else "(No prior knowledge base context.)"
    )

    rag_latency_ms = (time.monotonic() - start_ts) * 1000
    logger.info(
        "projects.upload_refined_prd.rag_complete",
        project_id=project_id,
        node_count=len(retrieved_nodes),
        latency_ms=round(rag_latency_ms, 2),
    )

    # --- Build full PRD text for open_questions prompt context ---
    # Exclude open_questions from the DOCX sections — it will be regenerated.
    sections_for_context: dict[str, str] = {
        k: v for k, v in prd_sections.items() if k != "open_questions"
    }
    prd_text_for_prompt = "\n\n".join(
        f"### {k.upper()}\n{v}" for k, v in sections_for_context.items() if v
    )

    # --- Regenerate open_questions via AI ---
    system_open_questions = (
        "You are a senior product manager writing a PRD. "
        "Your task is to write the OPEN QUESTIONS & RISKS section.\n\n"
        "This section has TWO required subsections — NEVER omit either:\n\n"
        "TYPE 1 — KB Conflicts (structured ConflictEntry objects):\n"
        "  Examine each knowledge base chunk provided. Identify direct contradictions between\n"
        "  what the transcript proposes and what existing PRDs state. For each conflict:\n"
        "    - source_prd_id: the doc_id from the KB chunk (e.g. 'payments-2024-01-15')\n"
        "    - conflicting_statement: quote the conflicting claim from the KB\n"
        "    - proposed_change: what the transcript proposes instead\n"
        "    - severity: 'blocking' | 'needs_discussion' | 'minor'\n"
        "    - kb_excerpt: copy verbatim the 1-3 sentences from the KB chunk that show the conflict.\n"
        "      Use the exact text from the [Source: ...] sections provided above.\n"
        "  If there are no conflicts, return an empty list — do NOT hallucinate conflicts.\n\n"
        "TYPE 2 — Transcript Gaps (GapEntry objects):\n"
        "  List questions about ambiguities, missing details, or decisions the PRD\n"
        "  left unresolved (e.g. scope boundaries, technical approach, compliance requirements).\n"
        "  For each gap:\n"
        "    - question: the gap as a clear, answerable question\n"
        "    - transcript_excerpt: copy 1-2 verbatim sentences from the PRD that prompted\n"
        "      this question. If the gap comes from complete absence of information, use an empty string.\n\n"
        "Ground every conflict in the KB context. Mark anything inferred as '(inferred)'."
    )
    user_open_questions = (
        f"PRD CONTENT (user-refined upload):\n{prd_text_for_prompt}\n\n"
        f"KNOWLEDGE BASE CONTEXT (prior PRDs — check these for Type 1 conflicts):\n{rag_context}\n\n"
        "Write the Open Questions & Risks section. Include both Type 1 conflicts and Type 2 gaps."
    )

    try:
        oq_result, _inp, _out = await generate_section(
            section_name="open_questions",
            section_model=OpenQuestionsSection,
            system_prompt=system_open_questions,
            user_prompt=user_open_questions,
            project_id=project_id,
        )
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=f"Open questions generation failed: {exc}",
        ) from exc

    # --- Build new prd_json payload ---
    # Shape each parsed section into its stored nested dict format.
    new_prd_json: dict = {}
    for key, text in sections_for_context.items():
        new_prd_json[key] = _build_section_dict(key, text)

    # Always use the freshly generated open_questions (never from DOCX).
    new_prd_json["open_questions"] = oq_result.model_dump()

    # --- Persist to DB + reset status if needed ---
    was_approved: bool = project.status == WorkflowStatus.PRD_APPROVED
    project.prd_json = json.dumps(new_prd_json)

    if was_approved:
        # Reset to PRD_GENERATED so user must re-approve the refined PRD
        # before stories can be generated.
        project.status = WorkflowStatus.PRD_GENERATED

    db.add(project)
    db.commit()
    db.refresh(project)

    logger.info(
        "projects.upload_refined_prd.complete",
        project_id=project_id,
        sections_parsed=list(prd_sections.keys()),
        was_approved=was_approved,
        new_status=project.status.value,
        type1_conflicts=len(oq_result.type1_conflicts),
        type2_gaps=len(oq_result.type2_gaps),
    )

    return {
        "project_id": project_id,
        "status": project.status.value,
        "open_questions": oq_result.model_dump(),
    }
