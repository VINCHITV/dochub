logger = structlog.get_logger()

router = APIRouter()

# ---------------------------------------------------------------------------
# Allowed statuses for refined-PRD upload
# ---------------------------------------------------------------------------
_REFINED_PRD_ALLOWED_STATUSES: frozenset[WorkflowStatus] = frozenset(
    {WorkflowStatus.PRD_GENERATED, WorkflowStatus.PRD_APPROVED}
)

# ---------------------------------------------------------------------------
# Section-key → prd_json field-dict converter
#
# parse_docx_by_headings() already returns snake_case keys via _match_section
# (e.g. "title", "description", "problem", "why", "success", "audience",
# "open_questions").  We only need to shape the flat text into the nested dict
# that prd_json stores for each section model.
# ---------------------------------------------------------------------------


def _build_section_dict(key: str, text: str) -> dict:
    """
    Convert a plain-text section body to the nested dict format stored in prd_json.

    The shape must match the corresponding Pydantic section model so that the
    frontend and story-generation prompts can deserialise it without errors.

    open_questions is intentionally excluded — it is always regenerated by AI.
    source_doc_ids is always empty on re-upload (no RAG assignment for static sections).
    """
    if key == "title":
        # TitleSection: {"title": str, "subtitle": None}
        # Heuristic: if the text contains " — ", treat the rest as subtitle.
        parts = text.split(" — ", 1)
        return {
            "title": parts[0].strip(),
            "subtitle": parts[1].strip() if len(parts) > 1 else None,
        }

    if key == "description":
        # DescriptionSection: {"overview": str, "source_doc_ids": []}
        return {"overview": text, "source_doc_ids": []}

    if key == "problem":
        # ProblemSection: {"problem_statement": str, "pain_points": [], "source_doc_ids": []}
        # Heuristic: lines starting with "- " or "• " are pain points.
        lines = text.splitlines()
        bullets: list[str] = []
        prose_lines: list[str] = []
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("- ") or stripped.startswith("• "):
                bullets.append(stripped.lstrip("-• ").strip())
            else:
                prose_lines.append(stripped)
        return {
            "problem_statement": "\n".join(prose_lines).strip() or text,
            "pain_points": bullets,
            "source_doc_ids": [],
        }

    if key == "why":
        # WhySection: {"rationale": str, "business_value": str, "source_doc_ids": []}
        # Split at first blank line — first block = rationale, rest = business_value.
        paragraphs = [p.strip() for p in text.split("\n\n", 1) if p.strip()]
        return {
            "rationale": paragraphs[0] if paragraphs else text,
            "business_value": paragraphs[1] if len(paragraphs) > 1 else "",
            "source_doc_ids": [],
        }

    if key == "success":
        # SuccessSection: {"metrics": [], "kpis": [], "source_doc_ids": []}
        # Treat all bullet lines as metrics; no KPI inference from plain text.
        lines = text.splitlines()
        items = [l.strip().lstrip("-• ").strip() for l in lines if l.strip()]
        return {"metrics": items, "kpis": [], "source_doc_ids": []}

    if key == "audience":
        # AudienceSection: {"primary_audience": str, "secondary_audience": None,
        #                    "personas": [], "source_doc_ids": []}
        paragraphs = [p.strip() for p in text.split("\n\n", 1) if p.strip()]
        return {
            "primary_audience": paragraphs[0] if paragraphs else text,
            "secondary_audience": paragraphs[1] if len(paragraphs) > 1 else None,
            "personas": [],
            "source_doc_ids": [],
        }

    # Fallback for any unrecognised key: store as raw text under a "content" key.
    return {"content": text, "source_doc_ids": []}


@router.get("/{project_id}")
async def get_project(
    project_id: str,
    db: Annotated[Session, Depends(get_session)],
) -> dict:
    """Return a Project row as JSON for frontend rehydration."""
    statement = select(Project).where(Project.id == project_id)
    project: Optional[Project] = db.exec(statement).first()

    if project is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Project '{project_id}' not found.",
        )

    prd_parsed: Optional[dict] = None
    if project.prd_json:
        try:
            prd_parsed = json.loads(project.prd_json)
        except json.JSONDecodeError:
            prd_parsed = None

    qa_answers: dict = {}
    if project.qa_answers:
        try:
            qa_answers = json.loads(project.qa_answers)
        except json.JSONDecodeError:
            qa_answers = {}

    return {
        "id": project.id,
        "name": project.name,
        "created_by": project.created_by,
        "status": project.status.value,
        "transcript_text": project.transcript_text,
        "prd_json": prd_parsed,
        "qa_answers": qa_answers,
        "prompt_version": project.prompt_version,
        "generator_model": project.generator_model,
        "embedding_model": project.embedding_model,
        "extractor_model": project.extractor_model,
        "created_at": project.created_at.isoformat(),
    }


@router.post("/{project_id}/approve", status_code=status.HTTP_200_OK)
async def approve_prd(
    project_id: str,
    db: Annotated[Session, Depends(get_session)],
) -> dict:
    """Advance PRD_GENERATED → PRD_APPROVED."""
    updated_project = advance_status(
        project_id=project_id,
        expected_current=WorkflowStatus.PRD_GENERATED,
        db=db,
    )
    logger.info("projects.prd_approved", project_id=project_id)
    return {"status": updated_project.status.value, "project_id": project_id}


@router.post("/{project_id}/qa-answers", status_code=status.HTTP_200_OK)
async def save_qa_answers(
    project_id: str,
    db: Annotated[Session, Depends(get_session)],
    answers: Annotated[dict, Body(embed=False)],
) -> dict:
    """
    Persist user-provided answers to open questions / gaps / conflicts.

    Merges the incoming `answers` dict into any previously saved answers
    (new keys are added, existing keys are overwritten). Answers are stored
    as a JSON blob on Project.qa_answers for future PRD refinement (B3 loop).

    The endpoint is intentionally permissive about project status — answers
    can be saved at any point after a PRD has been generated.

    Request body: flat JSON object mapping question text → answer string.
    Response: { "project_id": str, "saved": int }
    """
    statement = select(Project).where(Project.id == project_id)
    project: Optional[Project] = db.exec(statement).first()

    if project is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Project '{project_id}' not found.",
        )

    # Merge with existing answers
    existing: dict = {}
    if project.qa_answers:
        try:
            existing = json.loads(project.qa_answers)
        except json.JSONDecodeError:
            existing = {}

    merged = {**existing, **answers}
    project.qa_answers = json.dumps(merged)
    db.add(project)
    db.commit()

    logger.info(
        "projects.qa_answers_saved",
        project_id=project_id,
        answer_count=len(merged),
    )
    return {"project_id": project_id, "saved": len(merged)}


